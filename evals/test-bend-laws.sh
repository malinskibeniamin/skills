# install-bend.sh: a pinned release whose checksum does not match is never installed.
_bl_mirror="$_bl_tmp/mirror"
_bl_ver=$(sed -n 's/^VER="\(.*\)"$/\1/p' "$TEMPLATES/install-bend.sh")
case "$(uname -s)-$(uname -m)" in
  Darwin-arm64) _bl_target=darwin-arm64 ;;
  Darwin-x86_64) _bl_target=darwin-x64 ;;
  Linux-aarch64 | Linux-arm64) _bl_target=linux-arm64 ;;
  *) _bl_target=linux-x64 ;;
esac
mkdir -p "$_bl_mirror/v$_bl_ver" "$_bl_tmp/pkg/bend/bin" "$_bl_tmp/pkg/bend/bend2" "$_bl_tmp/pkg/bend/guide"
printf '#!/bin/sh\necho "bend %s"\n' "$_bl_ver" > "$_bl_tmp/pkg/bend/bin/bend"
chmod +x "$_bl_tmp/pkg/bend/bin/bend"
tar -czf "$_bl_mirror/v$_bl_ver/bend-$_bl_ver-$_bl_target.tar.gz" -C "$_bl_tmp/pkg" bend
_bl_home="$_bl_tmp/home"
mkdir -p "$_bl_home/bin"
printf '#!/bin/sh\necho "bend 0.0.1"\n' > "$_bl_home/bin/bend"
chmod +x "$_bl_home/bin/bend"
_bl_out=$(BEND_HOME="$_bl_home" BEND_MIRROR="file://$_bl_mirror" "$TEMPLATES/install-bend.sh" 2>&1) && _bl_code=0 || _bl_code=$?
if [ "$_bl_code" -ne 0 ] && printf '%s' "$_bl_out" | grep -q 'sha256' && "$_bl_home/bin/bend" version | grep -q '0.0.1'; then
  _bl_pass "install-bend.sh refuses a release whose sha256 differs and keeps the old install"
else
  _bl_fail "install-bend.sh refuses a release whose sha256 differs and keeps the old install" "exit $_bl_code: $_bl_out"
fi
printf '#!/bin/sh\necho "bend %s"\n' "$_bl_ver" > "$_bl_home/bin/bend"
_bl_out=$(BEND_HOME="$_bl_home" BEND_MIRROR="file://$_bl_tmp/nowhere" "$TEMPLATES/install-bend.sh" 2>&1) && _bl_code=0 || _bl_code=$?
if [ "$_bl_code" -eq 0 ] && printf '%s' "$_bl_out" | grep -q 'already installed'; then
  _bl_pass "install-bend.sh skips the download when the pinned version is installed"
else
  _bl_fail "install-bend.sh skips the download when the pinned version is installed" "exit $_bl_code: $_bl_out"
fi

rm -rf "$_bl_tmp"
