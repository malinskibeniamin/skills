_bl_pass() { echo "  PASS  $1"; PASS=$((PASS + 1)); }
_bl_fail() { echo "  FAIL  $1${2:+ ($2)}"; FAIL=$((FAIL + 1)); ERRORS="$ERRORS\n  FAIL: $1"; }

_bl_tmp=$(mktemp -d)
_bl_stub="$_bl_tmp/stub"
mkdir -p "$_bl_stub"
cat > "$_bl_stub/bend" <<'STUB'
#!/bin/sh
echo "$*" >> "$STUB_LOG"
[ "$1" = version ] && { echo "bend 2.0.37"; exit 0; }
file=$1
shift
case "$file" in
  */PROOF.bend)
    [ -n "${STUB_PROOF_FAILS:-}" ] && { echo "SOME PROOFS FAIL"; exit 1; }
    echo "${STUB_PROOF_SAYS:-ALL PROOFS CHECK}"
    ;;
  */oracle.bend)
    printf 'process.stdout.write(%s)\n' "$(printf '%s' "$STUB_TABLE" | node -e 'process.stdout.write(JSON.stringify(require("fs").readFileSync(0, "utf8")))')" > "$2"
    ;;
esac
STUB
chmod +x "$_bl_stub/bend"
export STUB_LOG="$_bl_tmp/bend.log"
export STUB_TABLE='# @generated by oracle.bend. DO NOT EDIT: run laws/check.sh --write
manual missing ask
auto missing ask
'

# A fresh laws/ tree holding one rule whose laws, model and proof are all clean.
_bl_fixture() {
  _bl_laws="$_bl_tmp/repo-$1/laws"
  mkdir -p "$_bl_laws/modes"
  cp "$TEMPLATES/check.sh" "$_bl_laws/check.sh"
  printf 'import ./policy.bend as P\n\ndef is_yes(h: P.Hint) -> Bool:\n  match h:\n    case P.Yes{}:\n      True{}\n    case _:\n      False{}\n' > "$_bl_laws/modes/LAWS.bend"
  printf 'def size(xs: List<&2, Nat>) -> Nat:\n  match xs:\n    case Nil{}:\n      0n\n    case h <> t:\n      1n+size(t)\n' > "$_bl_laws/modes/policy.bend"
  printf 'import ./LAWS.bend as Laws\n' > "$_bl_laws/modes/PROOF.bend"
  printf 'def main() -> IO(Unit):\n' > "$_bl_laws/modes/oracle.bend"
  printf '%s' "$STUB_TABLE" > "$_bl_laws/modes/decisions.txt"
}

# _bl_expect <description> <expected exit> <output pattern> -- <check.sh args>
_bl_expect() {
  local desc="$1" want="$2" pattern="$3" out code=0
  shift 4
  out=$(PATH="$_bl_stub:$PATH" "$_bl_laws/check.sh" "$@" 2>&1) || code=$?
  if [ "$code" -ne "$want" ]; then
    _bl_fail "$desc" "exit $code, want $want: $(printf '%s' "$out" | head -3 | tr '\n' ' ')"
  elif [ -n "$pattern" ] && ! printf '%s' "$out" | grep -qE -- "$pattern"; then
    _bl_fail "$desc" "output lacks /$pattern/: $(printf '%s' "$out" | head -3 | tr '\n' ' ')"
  else
    _bl_pass "$desc"
  fi
}

