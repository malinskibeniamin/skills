#!/usr/bin/env python3
"""Import REA's release-matched instructions, never its executable runtime."""

import argparse
import base64
import hashlib
import io
import json
import re
import shutil
import stat
import sys
import tarfile
import tempfile
from pathlib import Path, PurePosixPath


REPOSITORY = "https://github.com/morluto/rea"
NAME = "reverse-engineer-anything"
REGISTRATION = f"./{NAME}/"
SKILL = f"skills/{NAME}/SKILL.md"
REQUIRED = {"LICENSE", "THIRD_PARTY_NOTICES.md", "package.json", SKILL}
MAX_ARCHIVE_BYTES = 32 * 1024 * 1024
MAX_SKILL_BYTES = 4 * 1024 * 1024
ADAPTER = '''---
name: reverse-engineer-anything
description: "Use REA to inspect shipped binaries, packages, JavaScript/Electron artifacts or requested runtime evidence. Not ordinary source-repository exploration."
---

<!-- Generated by scripts/vendor-rea.py; do not edit. -->

Read [host compatibility and optional connection](../shared/REA.md) first.
It overrides conflicting upstream instructions. Then read the complete
[release-matched skill](../vendor/rea/skills/reverse-engineer-anything/SKILL.md).
Resolve its relative references from that directory.

Reuse connected tools and their actual schemas. Loading this skill grants no
installation, configuration, browser/process access, target execution, mutation,
delegation or background-work permission. Preserve the requested target and scope.
'''


def mcp_config(version):
    return ('{\n  "mcpServers": {\n    "rea": {\n      "command": "npx",\n'
            f'      "args": ["-y", "rea-agents@{version}", "mcp"]\n'
            '    }\n  }\n}\n')


def guard_paths(repo):
    for name in ("vendor/rea", "vendor/rea.lock.json", NAME,
                 "config/rea.mcp.json", ".claude-plugin/plugin.json"):
        path = repo / name
        while path != repo:
            if path.is_symlink():
                raise ValueError(f"Symlinked managed path: {path.relative_to(repo)}")
            path = path.parent
    for name in ("vendor", "vendor/rea", NAME, "config", ".claude-plugin"):
        path = repo / name
        if path.exists() and not path.is_dir():
            raise ValueError(f"Managed directory blocked by a file: {name}")
    for name in ("vendor/rea.lock.json", "config/rea.mcp.json", ".claude-plugin/plugin.json"):
        path = repo / name
        if path.exists() and not path.is_file():
            raise ValueError(f"Managed file blocked by a directory: {name}")


def inventory(root):
    files = {}
    if root.is_symlink():
        raise ValueError(f"Symlinked snapshot: {root}")
    for path in sorted(root.rglob("*")):
        mode = path.lstat().st_mode
        if stat.S_ISDIR(mode):
            continue
        if not stat.S_ISREG(mode):
            raise ValueError(f"Non-regular managed file: {path}")
        files[path.relative_to(root).as_posix()] = {
            "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
            "mode": stat.S_IMODE(mode),
        }
    return files


def validate_pin(revision, integrity):
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("Revision must be a reviewed full lowercase commit SHA")
    if not re.fullmatch(r"sha512-[A-Za-z0-9+/]{86}==", integrity):
        raise ValueError("Integrity must be an npm sha512 digest")


def release_metadata(payload):
    if not REQUIRED <= payload.keys():
        raise ValueError("Release must include the complete skill, package metadata and licenses")
    metadata = json.loads(payload["package.json"][0])
    version = metadata["version"]
    if (metadata["name"] != "rea-agents" or metadata["license"] != "MIT"
            or not re.fullmatch(r"\d+\.\d+\.\d+", version)
            or not isinstance(metadata["engines"]["node"], str)):
        raise ValueError("Expected a stable MIT rea-agents release with Node requirements")
    if not payload["LICENSE"][0].startswith(b"MIT License\n"):
        raise ValueError("Review the changed upstream license before importing")
    skills = {path for path in payload if PurePosixPath(path).name == "SKILL.md"}
    if skills != {SKILL} or any(path.startswith("skills/") and not path.startswith(f"skills/{NAME}/")
                                for path in payload):
        raise ValueError("Unreviewed upstream skill inventory")
    frontmatter = re.match(r"---\n(.*?)\n---\n", payload[SKILL][0].decode(), re.S)
    if (not frontmatter or not re.search(rf"^name: {NAME}$", frontmatter[1], re.M)
            or not re.search(r"^description: .+", frontmatter[1], re.M)
            or re.search(r"^disable-model-invocation:", frontmatter[1], re.M)):
        raise ValueError("Unreviewed skill metadata or invocation policy")
    for name, (data, _) in payload.items():
        if not name.startswith("skills/") or not name.endswith(".md"):
            continue
        for link in re.findall(r"\]\(([^)]+)\)", data.decode()):
            if link.startswith(("https://", "http://", "#")):
                continue
            reference = link.split("#", 1)[0]
            target = PurePosixPath(name).parent / reference
            if reference and (target.as_posix() not in payload or ".." in target.parts):
                raise ValueError(f"Missing or escaping skill reference: {name}: {link}")
    return version, metadata["engines"]["node"]


def read_archive(path, integrity):
    if path.stat().st_size > MAX_ARCHIVE_BYTES:
        raise ValueError("Release archive exceeds the import byte budget")
    archive_bytes = path.read_bytes()
    actual = "sha512-" + base64.b64encode(hashlib.sha512(archive_bytes).digest()).decode()
    if actual != integrity:
        raise ValueError("Release archive integrity mismatch")
    payload = {}
    total = 0
    # Read selected bytes only. Never extract paths or execute package scripts.
    with tarfile.open(fileobj=io.BytesIO(archive_bytes), mode="r:gz") as archive:
        for member in archive:
            parts = PurePosixPath(member.name).parts
            if (not parts or parts[0] != "package" or ".." in parts
                    or PurePosixPath(member.name).is_absolute()
                    or member.name != PurePosixPath(member.name).as_posix()):
                raise ValueError(f"Unsafe release path: {member.name}")
            name = PurePosixPath(*parts[1:]).as_posix()
            if member.isdir():
                continue
            if not (name.startswith("skills/") or name in REQUIRED):
                continue
            total += member.size
            if (not member.isfile() or member.mode not in (0o644, 0o755)
                    or member.size < 0 or total > MAX_SKILL_BYTES or name in payload):
                raise ValueError(f"Unsafe, oversized or duplicate release entry: {member.name}")
            stream = archive.extractfile(member)
            if stream is None:
                raise ValueError(f"Unreadable release entry: {member.name}")
            payload[name] = (stream.read(), member.mode)
    release_metadata(payload)
    return payload


def registration(manifest):
    return [entry for entry in manifest["skills"] if PurePosixPath(entry).name == NAME]


def check(repo):
    guard_paths(repo)
    lock = json.loads((repo / "vendor/rea.lock.json").read_text())
    validate_pin(lock["revision"], lock["integrity"])
    if lock["repository"] != REPOSITORY:
        raise ValueError("Upstream repository drifted")
    source = repo / "vendor/rea"
    files = inventory(source)
    if files != lock["files"]:
        raise ValueError("Snapshot bytes, modes or inventory drifted")
    version, node = release_metadata({name: ((source / name).read_bytes(), row["mode"])
                                      for name, row in files.items()})
    if (version != lock["version"] or node != lock["node"]
            or lock["tarball"] != f"https://registry.npmjs.org/rea-agents/-/rea-agents-{version}.tgz"):
        raise ValueError("Release metadata drifted")
    expected_adapter = {"SKILL.md": {"sha256": hashlib.sha256(ADAPTER.encode()).hexdigest(), "mode": 0o644}}
    if inventory(repo / NAME) != expected_adapter:
        raise ValueError("Skill adapter drifted")
    config = repo / "config/rea.mcp.json"
    if config.read_text() != mcp_config(version) or stat.S_IMODE(config.stat().st_mode) != 0o644:
        raise ValueError("Opt-in MCP config drifted from the skill release")
    manifest = json.loads((repo / ".claude-plugin/plugin.json").read_text())
    if registration(manifest) != [REGISTRATION]:
        raise ValueError("REA must have exactly one host skill owner")
    print(f"OK: REA {version}; {len(files)} release files, adapter and opt-in MCP pin verified")
    return lock


def install(repo, archive, revision, integrity):
    guard_paths(repo)
    validate_pin(revision, integrity)
    payload = read_archive(archive, integrity)
    version, node = release_metadata(payload)
    destination = repo / "vendor/rea"
    lock_path = repo / "vendor/rea.lock.json"
    if lock_path.exists():
        check(repo)
    elif any(path.exists() for path in (destination, repo / NAME, repo / "config/rea.mcp.json")):
        raise ValueError("Import would overwrite unmanaged files")
    manifest_path = repo / ".claude-plugin/plugin.json"
    manifest = json.loads(manifest_path.read_text())
    if registration(manifest) and not lock_path.exists():
        raise ValueError("Import would collide with an existing skill owner")
    repo.joinpath("vendor").mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="rea-import-", dir=repo / "vendor") as temp:
        stage = Path(temp) / "source"
        stage.mkdir()
        for name, (data, mode) in payload.items():
            target = stage / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            target.chmod(mode)
        lock = {"repository": REPOSITORY, "revision": revision, "version": version,
                "node": node, "tarball": f"https://registry.npmjs.org/rea-agents/-/rea-agents-{version}.tgz",
                "integrity": integrity, "files": inventory(stage)}
        if destination.exists():
            shutil.rmtree(destination)
        shutil.move(str(stage), destination)
    adapter = repo / NAME / "SKILL.md"
    config = repo / "config/rea.mcp.json"
    for path, text in ((adapter, ADAPTER), (config, mcp_config(version))):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        path.chmod(0o644)
    lock_path.write_text(json.dumps(lock, indent=2) + "\n")
    if not registration(manifest):
        manifest["skills"].append(REGISTRATION)
        manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    check(repo)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--archive", type=Path, help="reviewed published rea-agents .tgz (not a source checkout)")
    parser.add_argument("--revision", help="full source commit from the release's npm provenance")
    parser.add_argument("--integrity", help="independently reviewed npm dist.integrity (sha512)")
    parser.add_argument("--check", action="store_true", help="offline, read-only verification")
    args = parser.parse_args()
    if args.check:
        if args.archive or args.revision or args.integrity:
            parser.error("--check reads local state; omit release inputs")
        check(args.repo_root.resolve())
    else:
        if not all((args.archive, args.revision, args.integrity)):
            parser.error("refresh requires --archive, --revision and --integrity")
        install(args.repo_root.resolve(), args.archive, args.revision, args.integrity)


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, KeyError, TypeError, tarfile.TarError) as error:
        print(f"error: {error}", file=sys.stderr)
        sys.exit(1)
