#!/usr/bin/env python3
"""Import tstack's complete skills from a reviewed commit; retain the local full-send owner."""

import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path, PurePosixPath


REPOSITORY = "https://github.com/t3dotgg/tstack"
METADATA = {
    "babysit-pr": ("Monitor a PR through current CI and review feedback", "Monitor, watch, or babysit a PR through CI and review. Only when monitoring is requested."),
    "council": ("Review with explicitly requested cross-provider delegates", "Use for an explicit council request: three read-only reviewers from different providers. Never automatic delegation."),
    "file-pr": ("File a problem-first PR at the requested endpoint", "File or update a concise, problem-first PR through the existing publication workflow. Preserve requested draft state."),
    "full-send": ("Author delivery preset through an authorized merge", "Use the existing full-send owner; retain its endpoint and permission rules."),
    "full-stop": ("Deliver verified PR readiness without merging", "Use when the user requests full stop: delivery through verified readiness, never merge. Earlier narrower stops win."),
    "leaving-pr-comments": ("Post concise GitHub comments with verified attribution", "Use before posting GitHub PR comments, reviews, or replies on the user's behalf. Loading grants no posting permission."),
    "modernize": ("Reassess and safely refresh an older PR", "Use when asked to modernize or rebase an older PR. Assess whether its goal remains useful before updating the owned branch."),
    "sol-loop": ("Run an explicitly requested bounded Sol review loop", "Use for an explicit sol loop request: bounded read-only GPT Sol review rounds. Never automatic delegation."),
    "takeover": ("Finish inherited work while preserving contributor credit", "Use when asked to take over a PR, branch, or agent thread. Preserve authorship and the requested delivery endpoint."),
}


def git(source, *args):
    return subprocess.check_output(["git", "-C", str(source), *args])


def inventory(root):
    if root.is_symlink():
        raise ValueError(f"Symlinked managed directory: {root}")
    files = {}
    for path in sorted(root.rglob("*")):
        if path.is_symlink():
            raise ValueError(f"Symlinked managed file: {path}")
        if path.is_file():
            files[path.relative_to(root).as_posix()] = {
                "sha256": hashlib.sha256(path.read_bytes()).hexdigest(),
                "mode": path.stat().st_mode & 0o777,
            }
    return files


def discover(payload):
    names = set()
    for path, (data, _) in payload.items():
        if PurePosixPath(path).name != "SKILL.md":
            continue
        name = PurePosixPath(path).parent.name
        if name not in METADATA or path != f"skills/{name}/SKILL.md":
            raise ValueError(f"Unadapted upstream skill: {path}")
        if not re.match(rf"---\nname: {re.escape(name)}\n", data.decode("utf-8")):
            raise ValueError(f"Invalid upstream frontmatter: {path}")
        names.add(name)
    if names != set(METADATA) or not {"LICENSE", "README.md"} <= payload.keys():
        raise ValueError("All nine reviewed skills, LICENSE and README.md are required")
    return [{"name": name, "source": f"skills/{name}/SKILL.md",
             "registration": "./full-send/" if name == "full-send" else f"./tstack-skills/{name}/",
             "short_description": METADATA[name][0], "description": METADATA[name][1]}
            for name in sorted(names)]


def adapter(skill):
    return (f'---\nname: {skill["name"]}\ndescription: {json.dumps(skill["description"])}\n---\n\n'
            "<!-- Generated by scripts/vendor-tstack.py; do not edit. -->\n\n"
            "Read [host compatibility](../../shared/TSTACK.md) first, including the "
            f'`{skill["name"]}` branch. It overrides conflicting source instructions.\n\n'
            f'Read the complete [upstream skill](../../vendor/tstack/{skill["source"]}). '
            "Resolve relative references there. Load other skills through the host owners "
            "mapped in compatibility, not directly through snapshot siblings.\n")


def managed_paths(repo):
    for name in ("vendor", "vendor/tstack", "vendor/tstack.lock.json", "tstack-skills",
                 ".claude-plugin", ".claude-plugin/plugin.json"):
        if (repo / name).is_symlink():
            raise ValueError(f"Managed path must not be a symlink: {name}")


def check(repo):
    managed_paths(repo)
    lock = json.loads((repo / "vendor/tstack.lock.json").read_text())
    if lock["repository"] != REPOSITORY or not re.fullmatch(r"[0-9a-f]{40}", lock["revision"]):
        raise ValueError("Invalid upstream provenance")
    source = repo / "vendor/tstack"
    files = inventory(source)
    if files != lock["files"]:
        raise ValueError("Snapshot bytes, executable modes or inventory drifted")
    skills = discover({p: ((source / p).read_bytes(), r["mode"]) for p, r in files.items()})
    if skills != lock["skills"]:
        raise ValueError("Skill metadata drifted")
    expected = {f'{s["name"]}/SKILL.md': {"sha256": hashlib.sha256(adapter(s).encode()).hexdigest(), "mode": 0o644}
                for s in skills if s["name"] != "full-send"}
    if inventory(repo / "tstack-skills") != expected:
        raise ValueError("Adapter bytes, modes or inventory drifted")
    entries = json.loads((repo / ".claude-plugin/plugin.json").read_text())["skills"]
    registered = [p for p in entries if p.startswith("./tstack-skills/") or Path(p).name in METADATA]
    if sorted(registered) != sorted(s["registration"] for s in skills):
        raise ValueError("Each tstack skill must have exactly one host owner")
    print(f'OK: 9 skills, 8 adapters; {len(files)} files verified (pin {lock["revision"]})')
    return lock


def install(repo, source, revision):
    managed_paths(repo)
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("Revision must be a full lowercase commit SHA")
    if git(source, "rev-parse", f"{revision}^{{commit}}").decode().strip() != revision:
        raise ValueError("Revision must identify a commit")
    payload = {}
    for entry in git(source, "ls-tree", "-rz", revision).split(b"\0"):
        if not entry:
            continue
        header, raw_path = entry.split(b"\t", 1)
        path = raw_path.decode("utf-8")
        if not (path.startswith("skills/") or path in ("LICENSE", "README.md")):
            continue
        mode, kind, oid = header.decode().split()
        if PurePosixPath(path).is_absolute() or ".." in PurePosixPath(path).parts or kind != "blob" or mode not in ("100644", "100755"):
            raise ValueError(f"Unsafe upstream entry: {path}")
        payload[path] = (git(source, "cat-file", "blob", oid), int(mode[-3:], 8))
    skills = discover(payload)
    destination = repo / "vendor/tstack"
    adapters = repo / "tstack-skills"
    lock_path = repo / "vendor/tstack.lock.json"
    previous = check(repo) if lock_path.exists() else None
    if not previous and (destination.exists() or adapters.exists()):
        raise ValueError("Import would overwrite unmanaged files")
    manifest_path = repo / ".claude-plugin/plugin.json"
    manifest = json.loads(manifest_path.read_text())
    retained = [p for p in manifest["skills"] if not p.startswith("./tstack-skills/")]
    if retained.count("./full-send/") != 1 or not (repo / "full-send/SKILL.md").is_file():
        raise ValueError("The existing full-send owner must be registered exactly once")
    if {Path(p).name for p in retained} & (set(METADATA) - {"full-send"}):
        raise ValueError("Import would collide with an existing skill")
    repo.joinpath("vendor").mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory(dir=repo / "vendor", prefix=".tstack-import-") as temp:
        stage = Path(temp) / "source"
        stage.mkdir()
        for path, (data, mode) in payload.items():
            target = stage / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            target.chmod(mode)
        lock = {"repository": REPOSITORY, "revision": revision, "skills": skills, "files": inventory(stage)}
        if destination.exists():
            shutil.rmtree(destination)
        shutil.move(str(stage), destination)
    if adapters.exists():
        shutil.rmtree(adapters)
    for skill in skills:
        if skill["name"] == "full-send":
            continue
        directory = adapters / skill["name"]
        directory.mkdir(parents=True)
        (directory / "SKILL.md").write_text(adapter(skill))
        (directory / "SKILL.md").chmod(0o644)
    lock_path.write_text(json.dumps(lock, indent=2) + "\n")
    registrations = retained + [s["registration"] for s in skills if s["name"] != "full-send"]
    if manifest["skills"] != registrations:
        manifest["skills"] = registrations
        manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    check(repo)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo-root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--source", type=Path, help="separate upstream Git checkout")
    parser.add_argument("--revision", help="reviewed immutable commit SHA")
    parser.add_argument("--check", action="store_true", help="verify local snapshot without writing or networking")
    args = parser.parse_args()
    if args.check:
        if args.source or args.revision:
            parser.error("--check reads local state; omit --source and --revision")
        check(args.repo_root.resolve())
    else:
        if not args.source or not args.revision:
            parser.error("refresh requires --source and --revision")
        install(args.repo_root.resolve(), args.source.resolve(), args.revision)


if __name__ == "__main__":
    try:
        main()
    except (ValueError, OSError, KeyError, subprocess.CalledProcessError) as error:
        print(f"error: {error}", file=sys.stderr)
        sys.exit(1)
